#!/usr/bin/env python3
"""Generate TrismegistusUI's Theme+Palette.swift from the Endfield palette.json (read-only source).

  scripts/gen-palette.py ~/Projects/endfield-dotfiles/theme/palette.json
"""
import json, pathlib, sys

if len(sys.argv) != 2:
    sys.exit(f"usage: {sys.argv[0]} <palette.json>")
p = json.load(open(sys.argv[1]))
c = p["colors"]
ansi = p["terminal"]["ansi"]
names = ("paper", "raised", "sunken", "rule", "ink", "secondary", "muted", "yellow", "blue", "green", "magenta", "red", "borderInactive")
colors = [(k, c[k]["hex"]) for k in names]
# Terminal green and red are the darkened ANSI variants (readable as text on paper).
colors += [("terminalGreen", ansi[2]), ("terminalRed", ansi[1])]

out = [
    "// Generated by scripts/gen-palette.py from endfield-dotfiles/theme/palette.json. Do not edit.",
    "",
    "import SwiftUI",
    "",
    "extension Color {",
    "    init(hex: UInt32) {",
    "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255)",
    "    }",
    "}",
    "",
    "/// The Endfield palette (light mode only).",
    "public enum Theme {",
]
out += [f"    public static let {k} = Color(hex: 0x{h.lstrip('#').upper()})" for k, h in colors]
out += ["}", ""]
dest = pathlib.Path(__file__).resolve().parent.parent / "TrismegistusUI/Sources/TrismegistusUI/Theme+Palette.swift"
dest.write_text("\n".join(out))
print(f"wrote {dest}")
