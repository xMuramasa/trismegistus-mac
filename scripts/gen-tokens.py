#!/usr/bin/env python3
"""Generate TrismegistusUI's Tokens.swift from design/tokens.json and the Endfield palette.json (read-only source).

  scripts/gen-tokens.py ~/Projects/endfield-dotfiles/theme/palette.json design/tokens.json [out.swift]

Colours written {endfield.<name>} come from palette.json's `colors`, {color.palette.<name>} from tokens.json itself; an
unknown reference fails. The output defaults to TrismegistusUI/Sources/TrismegistusUI/Tokens.swift.
"""
import json, pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
if len(sys.argv) not in (3, 4):
    sys.exit(f"usage: {sys.argv[0]} <palette.json> <tokens.json> [out.swift]")
endfield = json.load(open(sys.argv[1]))["colors"]
tokens = json.load(open(sys.argv[2]))
dest = pathlib.Path(sys.argv[3]) if len(sys.argv) == 4 else root / "TrismegistusUI/Sources/TrismegistusUI/Tokens.swift"
fonts = root / "TrismegistusUI/Sources/TrismegistusUI/Resources/Fonts"


def camel(name):
    head, *rest = name.split("-")
    return head + "".join(w[:1].upper() + w[1:] for w in rest)


def pascal(name):
    c = camel(name)
    return c[:1].upper() + c[1:]


def ident(name):
    c = camel(name)
    return f"`{c}`" if c in ("default", "case", "in", "is", "as", "self") else c


def num(v):
    return repr(v) if isinstance(v, float) else str(v)


def hex_of(ref):
    """A #rrggbb, {endfield.x} or {color.palette.x} value as #RRGGBB."""
    m = re.fullmatch(r"\{(endfield|color\.palette)\.([\w-]+)\}", ref)
    if not m:
        if not re.fullmatch(r"#[0-9A-Fa-f]{6}", ref):
            sys.exit(f"not a colour or reference: {ref}")
        return ref.upper()
    group, name = m.groups()
    if group == "endfield":
        if name not in endfield or name.startswith("_"):
            sys.exit(f"unknown reference {ref}")
        return endfield[name]["hex"].upper()
    if name not in tokens["color"]["palette"]:
        sys.exit(f"unknown reference {ref}")
    return hex_of(tokens["color"]["palette"][name]["$value"])


def palette_ref(ref):
    """{color.palette.x} as `Palette.x` (roles point at the palette so the two stay one)."""
    m = re.fullmatch(r"\{color\.palette\.([\w-]+)\}", ref)
    if not m or m.group(1) not in tokens["color"]["palette"]:
        sys.exit(f"unknown reference {ref}")
    return f"Palette.{camel(m.group(1))}"


def leaves(group):
    return [(k, v) for k, v in group.items() if not k.startswith("$")]


def doc(token, indent):
    d = token.get("$description") if isinstance(token, dict) else None
    return [f"{indent}/// {d}"] if d else []


out = [
    "// Generated by scripts/gen-tokens.py from design/tokens.json and endfield-dotfiles/theme/palette.json. Do not edit.",
    "",
    "import SwiftUI",
    "",
    "extension Color {",
    "    init(hex: UInt32) {",
    "        self.init(.sRGB, red: Double((hex >> 16) & 0xFF) / 255, green: Double((hex >> 8) & 0xFF) / 255, blue: Double(hex & 0xFF) / 255)",
    "    }",
    "}",
    "",
    "/// `color.palette`: the Endfield colours and ours (light mode only). Views use the roles in `Ink` where one fits.",
    "public enum Palette {",
]
for name, t in leaves(tokens["color"]["palette"]):
    out += doc(t, "    ") + [f"    public static let {camel(name)} = Color(hex: 0x{hex_of(t['$value'])[1:]})"]
out += ["}", ""]


def role_value(v):
    return f"[{', '.join(palette_ref(r) for r in v)}]" if isinstance(v, list) else palette_ref(v)


def role_group(name, group, indent):
    """A role group as a struct with one instance, so call sites read `Ink.text.secondary`."""
    lines = [f"{indent}public struct {pascal(name)}: Sendable {{"]
    for k, t in leaves(group):
        lines += doc(t, indent + "    ") + [f"{indent}    public let {ident(k)} = {role_value(t['$value'])}"]
    return lines + [f"{indent}}}", f"{indent}public static let {ident(name)} = {pascal(name)}()"]


out += ["/// `color.role`: colours by job.", "public enum Ink {"]
for name, t in leaves(tokens["color"]["role"]):
    if "$value" in t:
        out += doc(t, "    ") + [f"    public static let {ident(name)} = {role_value(t['$value'])}"]
    else:
        out += role_group(name, t, "    ")
out += ["}", ""]

# Theme: source compatibility for App/ until #33 phase 2 moves it to Palette and Ink.
theme_aliases = {"steel": "Ink.bar.start", "steelDeep": "Ink.bar.middle", "steelEnd": "Ink.bar.end", "steelRule": "Ink.bar.rule"}
out += ["/// The old names (App/ until #33 phase 2): every palette colour, and the top bar's steel.", "public enum Theme {"]
out += [f"    public static let {camel(n)} = Palette.{camel(n)}" for n, _ in leaves(tokens["color"]["palette"])]
out += [f"    public static let {k} = {v}" for k, v in theme_aliases.items()]
out += ["}", ""]


def scalar_enum(group_name, swift_name, kind, summary):
    lines = [f"/// `{group_name}`: {summary}", f"public enum {swift_name} {{"]
    group = tokens[group_name]
    for name, t in leaves(group):
        v = t["$value"]
        if isinstance(v, dict):
            lines += doc(t, "    ") + [f"    public struct {pascal(name)}: Sendable {{"]
            lines += [f"        public let {ident(k)}: {kind} = {num(x)}" for k, x in v.items()]
            lines += ["    }", f"    public static let {ident(name)} = {pascal(name)}()"]
        else:
            lines += doc(t, "    ") + [f"    public static let {ident(name)}: {kind} = {num(v)}"]
    return lines + ["}", ""]


out += scalar_enum("opacity", "Opacity", "Double", "opacities.")
out += scalar_enum("space", "Space", "CGFloat", "the strict spacing scale; literals round up to the next step.")
out += scalar_enum("icon", "Icon", "CGFloat", "SF Symbol point sizes (and the square frames they sit in).")
out += scalar_enum("size", "Size", "CGFloat", "fixed sizes of rows, cards, panes and windows.")
out += scalar_enum("radius", "Radius", "CGFloat", "corner radii (Endfield is square; cards round one corner).")
out += scalar_enum("stroke", "Stroke", "CGFloat", "line widths and bars.")

out += [
    "/// A drop shadow (`View.shadow(_:)`).",
    "public struct ShadowToken: Sendable {",
    "    public let color: Color",
    "    public let radius: CGFloat",
    "    public let x: CGFloat",
    "    public let y: CGFloat",
    "}",
    "",
    "/// `shadow`.",
    "public enum Shadow {",
]
for name, t in leaves(tokens["shadow"]):
    v = t["$value"]
    color = f"{palette_ref(v['color'])}.opacity({num(v['opacity'])})"
    out += doc(t, "    ") + [f"    public static let {ident(name)} = ShadowToken(color: {color}, radius: {num(v['radius'])}, x: {num(v['x'])}, y: {num(v['y'])})"]
out += ["}", ""]

out += ["/// `motion`: an `Animation` where the token has a curve, else a `Duration` to wait (a value settling).", "public enum Motion {"]
for name, t in leaves(tokens["motion"]):
    v = t["$value"]
    if "curve" in v:
        value = f"Animation.{v['curve']}(duration: {num(v['duration'])})"
    else:
        value = f"Duration.milliseconds({round(v['duration'] * 1000)})"
    out += doc(t, "    ") + [f"    public static let {ident(name)} = {value}"]
out += ["}", ""]

# Fonts: each family's faces are the bundled TTFs <Family without spaces>-<Weight>.ttf, named by their PostScript name.
weights = {400: "Regular", 500: "Medium", 600: "SemiBold", 700: "Bold"}
families = leaves(tokens["font"]["family"])
out += ["/// `font.family`: the bundled families (Resources/Fonts, SIL OFL 1.1).", "public enum FontFamily: String, CaseIterable, Sendable {"]
out += [f"    case {ident(n)} = \"{t['$value']}\"" for n, t in families]
out += ["", "    /// PostScript names of the bundled faces, by weight.", "    var faces: [Int: String] {", "        switch self {"]
for n, t in families:
    stem = t["$value"].replace(" ", "")
    faces = []
    for w, wname in weights.items():
        ps = f"{stem}-{wname}"
        if not (fonts / f"{ps}.ttf").exists():
            sys.exit(f"missing font file {fonts / (ps + '.ttf')}")
        faces.append(f"{w}: \"{ps}\"")
    out += [f"        case .{ident(n)}: [{', '.join(faces)}]"]
out += ["        }", "    }", "}", ""]

roles = leaves(tokens["font"]["role"])
family_names = {n for n, _ in families}
out += ["/// `font.role`: the type roles (`View.typeRole(_:)`).", "public enum TypeRole: CaseIterable, Sendable {"]
out += [f"    case {', '.join(ident(n) for n, _ in roles)}", "", "    public var spec: TypeSpec {", "        switch self {"]
for n, t in roles:
    v = t["$value"]
    if v["family"] not in family_names or v["weight"] not in weights:
        sys.exit(f"font.role.{n}: unknown family or weight")
    out += [f"        case .{ident(n)}: TypeSpec(family: .{ident(v['family'])}, size: {num(v['size'])}, weight: {v['weight']}, "
            f"tracking: {num(v['tracking'])}, uppercase: {'true' if v['uppercase'] else 'false'})"]
out += ["        }", "    }", "}", ""]

dest.write_text("\n".join(out))
print(f"wrote {dest}")
